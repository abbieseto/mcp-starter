// Helper to generate realistic historical candlestick bars
export function generateCandles(basePrice: number, count: number = 40, volatility: number = 0.015, trend: number = 0.001): Candle[] {
  const candles: Candle[] = [];
  let current = basePrice * (1 - (trend * count) / 2);
  const now = Date.now();
  const stepMs = 3600 * 1000 * 4; // 4-hour bars

  for (let i = 0; i < count; i++) {
    const time = new Date(now - (count - i) * stepMs).toISOString();
    const open = current;
    const delta = (Math.random() - 0.48 + trend) * volatility * open;
    const close = Math.max(open * 0.5, open + delta);
    const high = Math.max(open, close) + Math.random() * volatility * 0.8 * open;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8 * open;
    const volume = Math.round((Math.random() * 50000 + 20000) * (basePrice > 500 ? 5 : 50));

    candles.push({
      timestamp: time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    current = close;
  }
  return candles;
}

// Helper to generate sparkline from base and variance
function generateSparkline(basePrice: number, changePct: number, points: number = 24): number[] {
  const arr: number[] = [basePrice * (1 - changePct / 100)];
  const trendStep = (basePrice * (changePct / 100)) / points;
  for (let i = 1; i < points - 1; i++) {
    const noise = (Math.random() - 0.5) * (basePrice * 0.008);
    arr.push(Number((arr[i - 1] + trendStep + noise).toFixed(2)));
  }
  arr.push(basePrice);
  return arr;
}

